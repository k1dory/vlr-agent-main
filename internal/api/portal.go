// portalSource marks users the /me portal created, so the Authentik auto-revoke
// webhook only ever deletes what the portal owns (never manually/bot-created ones).
const portalSource = "authentik"

// handlePortal is the central self-service subscription portal. It sits behind an
// Authentik forward-auth proxy that injects the authenticated email in
// cfg.PortalHeader (default X-Authentik-Email). The handler:
//
//  1. reads the trusted email (a browser cannot set it — the proxy overwrites it),
//  2. for EVERY portal node finds that user's key on the node, AUTO-PROVISIONING
//     one on first visit (create on the node → row + sub_token in PG),
//  3. renders one card per node (QR + subscription URL), so the user imports
//     every server and switches between them in the client.
//
// A node that fails to provision is shown as unavailable; the others still render.
// Mounted only when cfg.PortalEnabled().
func (s *Server) handlePortal(w http.ResponseWriter, r *http.Request) {
	if r.Method != http.MethodGet {
		http.Error(w, "method", http.StatusMethodNotAllowed)
		return
	}
	email := strings.TrimSpace(r.Header.Get(s.cfg.PortalHeader))
	if !looksLikeEmail(email) {
		http.Error(w, "forbidden: no authenticated identity", http.StatusForbidden)
		return
	}

	link, err := s.portalLink(r.Context(), email)
	if err != nil {
		s.log.Warn("portal lookup failed", "email", email, "err", err)
		http.Error(w, "lookup failed", http.StatusInternalServerError)
		return
	}
	if link.SubURL == "" {
		http.Error(w, "provisioning failed", http.StatusBadGateway)
		return
	}
	renderPortal(w, portalData{
		Email: email, Title: s.cfg.SubTitle, SubURL: link.SubURL, QR: qrSVG(link.SubURL),
		Servers: link.Servers, Missing: link.Missing,
	}, s)
}

// portalLinkInfo is one person's subscription as the portal shows it.
type portalLinkInfo struct {
	SubURL  string   // "" if no portal node could issue a key
	Servers []string // servers inside the subscription
	Missing []string // portal servers the person has no key on yet
}

// portalLink is the ONE place a person's link is decided: the SSO portal page
// and the ERP endpoint (POST /v1/links) both call it, so the same email always
// gets the same URL no matter where it was issued first. Keys are found by
// email (case-insensitive) and created on portal nodes that lack one.
func (s *Server) portalLink(ctx context.Context, email string) (portalLinkInfo, error) {
	keys, err := s.ensurePortalKeys(ctx, email, s.cfg.PortalProfile)
	if err != nil {
		return portalLinkInfo{}, err
	}
	// Any of the user's tokens serves every server; prefer the first portal
	// node's so the URL stays the one the user already imported.
	var info portalLinkInfo
	token := ""
	tokenOn := tokensByNode(keys)
	for i, n := range s.cfg.PortalNodes {
		name := cardName(n, i)
		if t, ok := tokenOn[n.ID]; ok {
			info.Servers = append(info.Servers, name)
			if token == "" {
				token = t
			}
		} else {
			info.Missing = append(info.Missing, name)
		}
	}
	info.SubURL = s.subURL(token)
	return info, nil
}

// tokensByNode maps node -> sub_token of the user's key there (first one wins,
// rows are ordered oldest first so the original key is kept stable).
func tokensByNode(users []store.UserRow) map[string]string {
	m := map[string]string{}
	for _, u := range users {
		if _, dup := m[u.NodeID]; !dup && u.SubToken != "" {
			m[u.NodeID] = u.SubToken
		}
	}
	return m
}

func cardName(n config.PortalNode, i int) string {
	if n.Name != "" {
		return n.Name
	}
	return "Сервер " + strconv.Itoa(i+1)
}

// subURL builds the public subscription URL for a token.
func (s *Server) subURL(token string) string {
	if s.cfg.SubBaseURL == "" || token == "" {
		return ""
	}
	return strings.TrimRight(s.cfg.SubBaseURL, "/") + "/sub/" + token
}

// looksLikeEmail is a cheap sanity check so an empty/garbage header never creates
// a junk user.
func looksLikeEmail(str string) bool {
	at := strings.IndexByte(str, '@')
	return at > 0 && at < len(str)-1 && !strings.ContainsAny(str, " \t\r\n")
}

// qrSVG renders url as an inline QR <svg>, or "" if it won't encode (page still
// shows the link text).
func qrSVG(url string) template.HTML {
	if url == "" {
		return ""
	}
	code, err := qr.Encode(url)
	if err != nil {
		return ""
	}
	return template.HTML(code.SVG(4, 4)) //nolint:gosec // generated by us, not user input
}

type portalData struct {
	Email   string
	Title   string
	SubURL  string
	QR      template.HTML
	Servers []string // servers inside the subscription
	Missing []string // portal servers the user has no key on yet
}

func renderPortal(w http.ResponseWriter, d portalData, s *Server) {
	w.Header().Set("Content-Type", "text/html; charset=utf-8")
	if err := portalTmpl.Execute(w, d); err != nil {
		s.log.Warn("portal render failed", "err", err)
	}
}

